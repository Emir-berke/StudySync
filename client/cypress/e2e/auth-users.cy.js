const password = 'E2ePassword123!'
const api = 'http://localhost:5050/api'

function login(email, destination = '/sessions') {
  cy.visit('/login')
  cy.get('#email').type(email)
  cy.get('#password').type(password, { log: false })
  cy.contains('button', 'Sign In').click()
  cy.location('pathname').should('eq', destination)
}

describe('SCRUM-11 auth and User integration with the real API', () => {
  beforeEach(() => { cy.clearLocalStorage(); cy.task('seedAuthUsers') })

  it('registers, restores, edits, protects, logs out and deletes a student account', () => {
    const email = `scrum11-${Date.now()}@example.test`
    cy.visit('/account')
    cy.location('pathname').should('eq', '/login')
    cy.visit('/register')
    cy.get('#name').type('E2E Student')
    cy.get('#email').type(email)
    cy.get('#password').type(password, { log: false })
    cy.get('#confirmPassword').type(password, { log: false })
    cy.contains('button', 'Sign Up').click()
    cy.location('pathname').should('eq', '/sessions')
    cy.reload()
    cy.contains('a', 'My Profile').click()
    cy.get('#email').should('have.value', email)
    cy.get('#name').clear().type('E2E Updated Student')
    cy.contains('button', 'Save changes').click()
    cy.contains('Profile updated.').should('be.visible')
    cy.reload()
    cy.get('#name').should('have.value', 'E2E Updated Student')
    cy.visit('/users')
    cy.location('pathname').should('eq', '/sessions')
    cy.window().then((win) => {
      const token = win.localStorage.getItem('studysync_token')
      cy.request({ url: `${api}/users`, headers: { Authorization: `Bearer ${token}` }, failOnStatusCode: false })
        .its('status').should('eq', 403)
    })
    cy.contains('button', 'Sign Out').click()
    cy.visit('/register')
    cy.get('#name').type('Duplicate Student')
    cy.get('#email').type(email)
    cy.get('#password').type(password, { log: false })
    cy.get('#confirmPassword').type(password, { log: false })
    cy.contains('button', 'Sign Up').click()
    cy.get('[role="alert"]').should('contain', 'already exists')
    cy.visit('/login')
    cy.get('#email').type(email)
    cy.get('#password').type('WrongPassword123!', { log: false })
    cy.contains('button', 'Sign In').click()
    cy.get('[role="alert"]').should('contain', 'Invalid email or password')
    cy.get('#password').clear().type(password, { log: false })
    cy.contains('button', 'Sign In').click()
    cy.location('pathname').should('eq', '/sessions')
    cy.contains('a', 'My Profile').click()
    cy.screenshot('student-profile-persisted')
    cy.window().then((win) => win.localStorage.setItem('studysync_token', 'expired-test-token'))
    cy.reload()
    cy.location('pathname').should('eq', '/login')
    login(email, '/account')
    cy.contains('a', 'My Profile').click()
    cy.on('window:confirm', () => true)
    cy.contains('button', 'Delete my account').click()
    cy.location('pathname').should('eq', '/login')
    cy.request({ method: 'POST', url: `${api}/auth/login`, body: { email, password }, failOnStatusCode: false })
      .its('status').should('eq', 401)
  })

  it('lets an admin read, edit and delete another disposable user', () => {
    const email = `scrum11-managed-${Date.now()}@example.test`
    cy.request('POST', `${api}/auth/register`, { name: 'Managed Student', email, password })
    login('scrum11-admin@example.test')
    cy.contains('a', 'Users').click()
    cy.contains('tr', email).within(() => cy.contains('button', 'Edit').click())
    cy.get('#user-name').clear().type('Managed Updated')
    cy.contains('button', 'Save user').click()
    cy.contains('User updated.').should('be.visible')
    cy.reload()
    cy.contains('tr', email).should('contain', 'Managed Updated')
    cy.screenshot('admin-user-crud')
    cy.on('window:confirm', () => true)
    cy.contains('tr', email).within(() => cy.contains('button', 'Delete').click())
    cy.contains('User deleted.').should('be.visible')
    cy.contains('td', email).should('not.exist')
  })
})
